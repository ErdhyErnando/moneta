/**
 * Generates `src/kumo-source.css` — the single `@source` line Tailwind needs to
 * scan kumo's compiled components.
 *
 * Why this exists (spike #44, caveat 1 / decision D10):
 *   - Tailwind v4 does not scan node_modules by default.
 *   - pnpm links packages, and the @tailwindcss/oxide scanner does NOT follow
 *     symlinks, so `node_modules/@cloudflare/kumo/dist` yields 0 files.
 *   - Globs inside a path segment (`@cloudflare+kumo@*`) are also rejected.
 *   - The real `.pnpm/@cloudflare/kumo@<version>_<peer-hash>/...` path works, but
 *     the hash changes on every install — hence a generated, gitignored file.
 *
 * The build must fail loudly when kumo is missing or the scan matches nothing,
 * because the failure mode is otherwise silent (unstyled dialogs/popovers).
 */
import fs from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const appRoot = path.resolve(here, "..");
const outFile = path.join(appRoot, "src", "kumo-source.css");
const require = createRequire(path.join(appRoot, "package.json"));

function fail(message) {
	console.error(`\n[kumo-source] ${message}\n`);
	console.error(
		"[kumo-source] Tailwind would scan 0 kumo files and component styles " +
			"would be missing. Refusing to continue.\n",
	);
	process.exit(1);
}

let pkgPath;
try {
	pkgPath = require.resolve("@cloudflare/kumo/package.json");
} catch {
	fail("@cloudflare/kumo is not installed — run `pnpm install` first.");
}

const distDir = path.join(path.dirname(pkgPath), "dist");
if (!fs.existsSync(distDir))
	fail(`kumo dist directory not found at ${distDir}`);

/** Count .js files under dist (recursive) so "0 candidates" is impossible. */
function countJs(dir) {
	let n = 0;
	for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
		const full = path.join(dir, entry.name);
		if (entry.isDirectory()) n += countJs(full);
		else if (entry.isFile() && entry.name.endsWith(".js")) n += 1;
	}
	return n;
}

const jsFiles = countJs(distDir);
if (jsFiles === 0) fail(`no JavaScript files under ${distDir}`);

// Emit the pattern relative to this CSS file (both live in src/).
const rel = path
	.relative(path.join(appRoot, "src"), distDir)
	.split(path.sep)
	.join("/");
if (!rel.startsWith(".")) fail(`unexpected relative path: ${rel}`);

const contents = `/* GENERATED by scripts/generate-kumo-source.mjs — do not edit, do not commit.
 * kumo dist: ${rel} (${jsFiles} JS files)
 */
@source "${rel}/**/*.js";
`;

const previous = fs.existsSync(outFile) ? fs.readFileSync(outFile, "utf8") : "";
// Only write on change so dev-server watchers don't reload needlessly.
if (previous !== contents) fs.writeFileSync(outFile, contents);

console.log(`[kumo-source] ok — ${jsFiles} kumo JS files scanned from ${rel}`);
